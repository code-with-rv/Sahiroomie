export const CountdownLabel: React.FC<{ initialSeconds: number }> = ({ initialSeconds }) => {
  const [remaining, setRemaining] = useState(initialSeconds);

  useEffect(() => {
    setRemaining(initialSeconds);
  }, [initialSeconds]);

  useEffect(() => {
    const id = setInterval(() => {
      setRemaining((s) => (s > 60 ? s - 60 : 0));
    }, 60000);
    return () => clearInterval(id);
  }, []);

  return <span className="font-mono-num">{formatCountdown(remaining)}</span>;
};
