export function getLocalizedCityLabel(cityId: string, lang: Language): string {
  if (cityId === 'All India') {
    if (lang === 'hi') return 'पूरा भारत';
    if (lang === 'kn') return 'ಸಂಪೂರ್ಣ ಭಾರತ';
    if (lang === 'mr') return 'संपूर्ण भारत';
    return 'All India';
  }
  const cObj = CITIES_DATA.find((c) => c.id === cityId);
  if (!cObj) return cityId;
  if (lang === 'hi') return cObj.hi;
  if (lang === 'kn') return cObj.kn;
  if (lang === 'mr') return cObj.mr;
  return cityId;
}

export function getLocalizedListingTitle(listing: Listing, lang: Language): string {
  if (lang === 'hi' && listing.titleHi) return listing.titleHi;
  if (lang === 'kn' && listing.titleKn) return listing.titleKn;
  if (lang === 'mr' && listing.titleMr) return listing.titleMr;
  return listing.title;
}

